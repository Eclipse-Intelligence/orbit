function parse(text: string) {
  return parseTaskText(text, SATURDAY_10_20);
}

describe("typed repeat corpus", () => {
  it("holds at least 300 to-dos", () => {
    assert.ok(REPEATS.length + PLAIN_BEFORE_REPEATS.length + UNSURE.length >= 300);
    assert.equal(new Set([...REPEATS.map(([text]) => text), ...PLAIN_BEFORE_REPEATS.map(([text]) => text), ...UNSURE]).size, REPEATS.length + PLAIN_BEFORE_REPEATS.length + UNSURE.length);
  });

  it("reads each repeat with its exact rule, first date, end and title", () => {
    for (const [text, want] of REPEATS) {
      const read = parse(text);
      assert.deepEqual(
        { unsure: read.unsure, title: read.title, due: read.due, repeat: read.repeat, remind: read.remindMinutes },
        { unsure: false, title: want.title, due: want.due, repeat: { rule: want.rule, ends: want.ends }, remind: want.remind ?? null },
        text,
      );
    }
  });

  it("reads to-dos that don't repeat exactly as before repeats", () => {
    for (const [text, want] of PLAIN_BEFORE_REPEATS) {
      const read = parse(text);
      assert.deepEqual(
        { title: read.title, due: read.due, unsure: read.unsure, remindMinutes: read.remindMinutes, durationMinutes: read.durationMinutes, guess: read.guess, lit: read.marks.map((mark) => text.slice(mark.start, mark.end)), repeat: read.repeat },
        { ...want, repeat: undefined },
        text,
      );
    }
  });

  it("leaves repeat words it can't settle unsure, with nothing lit and nothing saved", () => {
    for (const text of UNSURE) {
      const read = parse(text);
      assert.deepEqual({ unsure: read.unsure, title: read.title, due: read.due, repeat: read.repeat, marks: read.marks }, { unsure: true, title: text, due: null, repeat: undefined, marks: [] }, text);
    }
  });

  it("reads a long list of days in linear time", () => {
    for (const text of [`every Mon and ${"Mon and ".repeat(3000)}`, `Call ${"Mon and ".repeat(3000)}every day`]) {
      const started = performance.now();
      parse(text);
      assert.ok(performance.now() - started < 1500, text.slice(0, 30));
    }
  });
});
